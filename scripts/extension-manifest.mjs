/**
 * Whether a file under extension/ belongs in a packaged build. An allowlist,
 * so a signing key, .env or editor backup kept in the folder never ships:
 * only the extension's own file types, and nothing under a dotfile or
 * dot-directory. `path` is relative to extension/, with forward slashes.
 */
export function isPackagedFile(path) {
  if (path.split("/").some((part) => part.startsWith("."))) return false;
  return /\.(js|json|html|css|png)$/.test(path);
}

/** True for "prod" in any case; everything else is a dev build. */
export function isProdEnv(env) {
  return String(env ?? "").toLowerCase() === "prod";
}

const isDevHost = (pattern) => /^https?:\/\/(localhost|127\.0\.0\.1|\[::1\])(:\d+)?\//.test(pattern);

/**
 * Returns a copy of the checked-in manifest pointed at `apiBase` (a bare
 * origin) and named and keyed for `env`.
 *
 * @param {Record<string, any>} manifest
 * @param {{ apiBase: string, env: string, version?: string }} options
 * @returns {Record<string, any>}
 */
export function packagedManifest(manifest, { apiBase, env, version }) {
  const out = JSON.parse(JSON.stringify(manifest));
  out.host_permissions = [
    ...(out.host_permissions ?? []).filter((p) => !isDevHost(p)),
    `${apiBase}/*`,
  ];
  out.name = isProdEnv(env) ? "LeetPro" : "LeetPro (Dev)";
  if (isProdEnv(env)) delete out.key;
  else out.key = DEV_EXTENSION_KEY;
  if (version) out.version = version;
  return out;
}

/** The generated config.js the extension reads its API origin from. */
export function packagedConfig({ apiBase, env }) {
  return (
    `// Generated by LeetPro's extension packager. Do not edit.\n` +
    `self.LEETPRO_CONFIG = {\n  apiBase: ${JSON.stringify(apiBase)},\n  env: ${JSON.stringify(String(env).toLowerCase())},\n};\n`
  );
}

/**
 * Chrome's extension ID for a public key: the first 32 hex digits of
 * SHA-256(public key DER), each mapped 0-f to a-p.
 */
export function extensionIdFromKey(key) {
  const hex = createHash("sha256").update(Buffer.from(key, "base64")).digest("hex").slice(0, 32);
  return hex.replace(/./g, (h) => String.fromCharCode(97 + parseInt(h, 16)));
}

export const DEV_EXTENSION_ID = extensionIdFromKey(DEV_EXTENSION_KEY);
